// 공유 상태 — A와 B의 유일한 접점.
// 담당: 공동. 이 파일을 고칠 때는 반드시 상대에게 알린다.
//
// 문서로 합의하면 지켜지지 않는다. 파일이 있으면 둘 다 이걸 import 한다
// — docs/team-plan.html §03 이 8/5 병합 리스크의 대응책으로 지목한 것이 이 파일이다.
